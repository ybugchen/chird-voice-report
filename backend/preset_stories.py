def find_matching_story(topic: str, age_range: str = "3-6") -> dict:
    """Find the best matching preset story for the given topic.

    Uses keyword substring matching and title matching to score each story.
    Returns the highest-scoring story, or a random one if no match is found.
    """
    best_score = 0
    best_story = None

    for story in PRESET_STORIES:
        score = 0
        # Keyword matching
        for keyword in story["keywords"]:
            if keyword in topic:
                score += 1
        # Title matching
        if story["title"] in topic or topic in story["title"]:
            score += 2
        # Age range bonus
        if story["age_range"] == age_range:
            score += 0.5

        if score > best_score:
            best_score = score
            best_story = story

    if best_story is None:
        best_story = random.choice(PRESET_STORIES)

    return best_story
